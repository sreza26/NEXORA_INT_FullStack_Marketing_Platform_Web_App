import { useEffect, useState } from 'react'
import { Link, useSearchParams } from 'react-router-dom'
import { api, money } from '../../lib/api'
import { usePageTitle } from '../../lib/usePageTitle'

interface Commission {
  id: number
  transaction?: { reference?: string }
  generation: number
  rate: number
  base_amount: number
  amount: number
  status: string
  paid_at?: string
  created_at?: string
}

export default function Commissions() {
  usePageTitle('Commissions')
  const [searchParams] = useSearchParams()
  const status = searchParams.get('status') || ''
  const [commissions, setCommissions] = useState<Commission[]>([])
  const [totals, setTotals] = useState({ pending: 0, approved: 0, paid: 0, reversed: 0 })

  useEffect(() => {
    const url = status ? `/member/commissions?status=${status}` : '/member/commissions'
    api.get(url).then((res) => {
      setCommissions(res.data.items || res.data.commissions || [])
      if (res.data.totals) setTotals(res.data.totals)
      else {
        const items = res.data.items || []
        setTotals({
          pending: items.filter((i: any) => i.status === 'pending').reduce((a: number, b: any) => a + Number(b.amount || 0), 0),
          approved: items.filter((i: any) => i.status === 'approved').reduce((a: number, b: any) => a + Number(b.amount || 0), 0),
          paid: items.filter((i: any) => i.status === 'paid').reduce((a: number, b: any) => a + Number(b.amount || 0), 0),
          reversed: items.filter((i: any) => i.status === 'reversed').reduce((a: number, b: any) => a + Number(b.amount || 0), 0),
        })
      }
    }).catch(() => {
      setCommissions([])
    })
  }, [status])

  const filters = [
    { value: '', label: 'All' },
    { value: 'pending', label: 'Pending' },
    { value: 'approved', label: 'Approved' },
    { value: 'paid', label: 'Paid' },
    { value: 'reversed', label: 'Reversed' },
  ]

  const badgeClass = (s: string) => {
    if (s === 'paid') return 'badge-success'
    if (s === 'approved') return 'badge-info'
    if (s === 'pending') return 'badge-warn'
    if (s === 'reversed' || s === 'rejected') return 'badge-danger'
    return 'badge-muted'
  }

  return (
    <>
      <div>
        <h1 className="page-title">My commissions</h1>
        <p className="section-sub">Generation bonuses generated by verified sales in your downline.</p>
      </div>

      <div className="mt-6 grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <div className="stat-card">
          <span className="stat-label">pending</span>
          <span className="stat-value">{money(Number(totals.pending || 0))}</span>
        </div>
        <div className="stat-card">
          <span className="stat-label">approved</span>
          <span className="stat-value">{money(Number(totals.approved || 0))}</span>
        </div>
        <div className="stat-card">
          <span className="stat-label">paid</span>
          <span className="stat-value">{money(Number(totals.paid || 0))}</span>
        </div>
        <div className="stat-card">
          <span className="stat-label">reversed</span>
          <span className="stat-value">{money(Number(totals.reversed || 0))}</span>
        </div>
      </div>

      <div className="mt-5 flex flex-wrap gap-2">
        {filters.map((f) => (
          <Link key={f.value} to={f.value ? `/member/commissions?status=${f.value}` : '/member/commissions'} className={`filter-chip ${status === f.value ? 'filter-chip-active' : ''}`}>{f.label}</Link>
        ))}
      </div>

      <div className="mt-4 card overflow-hidden">
        <div className="table-wrap">
          <table className="data-table">
            <thead>
              <tr>
                <th>Transaction</th>
                <th className="text-right">Generation</th>
                <th className="text-right">Rate</th>
                <th className="text-right">Base</th>
                <th className="text-right">Amount</th>
                <th>Status</th>
                <th>Paid at</th>
              </tr>
            </thead>
            <tbody>
              {commissions.length === 0 ? (
                <tr><td colSpan={7} className="text-center text-slate-400">No commissions recorded yet.</td></tr>
              ) : (
                commissions.map((c: any) => (
                  <tr key={c.id}>
                    <td>
                      <Link to="/member/transactions" className="font-mono text-xs text-accent-600 hover:underline">
                        {c.transaction?.reference || c.reference || '—'}
                      </Link>
                    </td>
                    <td className="text-right">Gen {c.generation}</td>
                    <td className="text-right">{(Number(c.rate || 0) * 100).toFixed(2).replace(/\.00$/, '')}%</td>
                    <td className="text-right money">{money(Number(c.base_amount || 0))}</td>
                    <td className="text-right font-bold text-navy-900">{money(Number(c.amount || 0))}</td>
                    <td><span className={`badge ${badgeClass(c.status)}`}>{c.status}</span></td>
                    <td className="text-sm text-slate-500">{c.paid_at ? new Date(c.paid_at.replace(' ', 'T')).toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' }) : '—'}</td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>
    </>
  )
}
